/**
 * Skill definitions. A skill is data: costs and scaling per level plus an ActionDef timeline.
 * Scaled values use `[base, perLevel]` pairs: value(level) = base + perLevel × (level − 1).
 * Damage values are percentages of the actor's attack (or magic) power.
 */
import type { ActionDef } from '../combat/actions';
import type { WeaponType } from './items';
import type { Mods } from './statuses';
import type { PowerType } from './weapons';

export type SkillType = 'active' | 'buff' | 'passive';
export type Scaled = readonly [number, number];

export interface SkillDef {
  readonly id: string;
  /** Job that owns the skill. Descendant jobs can still use their ancestors' skills. */
  readonly job: string;
  readonly nameKey: string;
  readonly descKey: string;
  readonly type: SkillType;
  readonly maxLevel: number;
  /** Character level required to put the first point in. */
  readonly reqLevel: number;
  readonly prereq?: { readonly skill: string; readonly level: number };
  /** Weapon type that must be held (null = any). */
  readonly weapon: WeaponType | null;
  readonly power: PowerType;
  readonly mp: Scaled;
  readonly cooldown: Scaled;
  readonly damage: Scaled;
  /** Buff duration (s). */
  readonly duration?: Scaled;
  /** Buff magnitude / teleport distance / other skill-specific value. */
  readonly value?: Scaled;
  readonly action?: ActionDef;
  /** Status applied to the caster by buff skills (magnitude = value). */
  readonly status?: string;
  /** Passive modifiers per skill level. */
  readonly passive?: Mods;
  /** Icon art hint: glyph id + accent color. */
  readonly icon: { readonly glyph: string; readonly color: string };
}

export function scaled(v: Scaled | undefined, level: number): number {
  if (!v) return 0;
  return v[0] + v[1] * (Math.max(1, level) - 1);
}

